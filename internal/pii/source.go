package pii

import (
	_ "embed"
	"strings"
)

//go:embed scanner.go
var scannerSource string

// Standalone derives the CI program from the canonical scanner, without a
// second implementation or dependencies on the target repository's module.
func Standalone() string {
	return "// Code generated by fundamentum; DO NOT EDIT.\n" +
		strings.Replace(scannerSource, "package pii\n", "package main\n", 1) +
		"\nfunc main() { os.Exit(RunCLI(os.Args[1:], os.Stderr)) }\n"
}
